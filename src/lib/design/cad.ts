// Real downloadable files for the send-off flow, ported from the design
// prototype's B.cad (docs/design/js/sendoff.js).

export interface CadSpecs {
  width: number;
  depth: number;
  height: number;
}

export const DEFAULT_SPECS: CadSpecs = {
  width: 300,
  depth: 300,
  height: 300,
};

export function slug(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "") || "project"
  );
}

export function drawingKindFor(
  name: string,
): "espresso" | "register" | "device" {
  const n = name.toLowerCase();
  if (/espresso|coffee machine/.test(n)) return "espresso";
  if (/register|till|cash/.test(n)) return "register";
  return "device";
}

export function scad(name: string, s: CadSpecs = DEFAULT_SPECS): string {
  const kind = drawingKindFor(name);
  const [w, d, h] = [s.width, s.depth, s.height];
  let body = `// ${name} — generated by Bottega\n// Units: millimetres. Change the numbers below and re-render (F6) in OpenSCAD.\n// File > Export > STL to send to a maker. Ask for STEP if a machine shop needs it.\n\nwidth  = ${w};\ndepth  = ${d};\nheight = ${h};\nwall   = 2;   // sheet thickness\n\n`;
  if (kind === "espresso") {
    body += `group_dia = 58;     // standard portafilter\ntray_depth = 32 + 12; // +12 mm deeper, on rails\n\nmodule body() { difference() { cube([width, depth, height - 56]); translate([wall, wall, wall]) cube([width - 2*wall, depth - 2*wall, height]); } }\nmodule group_head(x) { translate([x, -10, height * 0.45]) rotate([-90,0,0]) cylinder(d = group_dia + 12, h = 30, $fn = 64); }\nmodule drip_tray() { translate([20, -tray_depth, 24]) cube([width - 40, tray_depth + 20, 30]); }\nmodule cup_rail() { translate([10, 10, height - 56]) difference() { cube([width - 20, depth - 20, 22]); translate([6,6,-1]) cube([width - 32, depth - 32, 30]); } }\n\nbody();\ngroup_head(width * 0.27);\ngroup_head(width * 0.73);\ndrip_tray();\ncup_rail();\n`;
  } else if (kind === "register") {
    body += `drawer_h = 70;\nslide_len = depth - 40;   // ball-bearing slides, 20 kg\n\ndifference() { cube([width, depth, height]); translate([20, -1, 15]) cube([width - 40, depth - 20, drawer_h]); }\ntranslate([24, 0, 17]) cube([width - 48, slide_len, drawer_h - 6]); // drawer\nfor (x = [12, width - 16]) translate([x, 20, 30]) cube([4, slide_len, 12]);  // slides\n`;
  } else {
    body += `difference() {\n  cube([width, depth, height]);\n  translate([wall, wall, wall]) cube([width - 2*wall, depth - 2*wall, height]); // hollow shell, open top\n}\n// TODO: your apprentice adds detailed parts here as the design firms up.\n`;
  }
  return body;
}

export function stl(name: string, s: CadSpecs = DEFAULT_SPECS): string {
  const [w, d, h] = [s.width, s.depth, s.height];
  const v = [
    [0, 0, 0],
    [w, 0, 0],
    [w, d, 0],
    [0, d, 0],
    [0, 0, h],
    [w, 0, h],
    [w, d, h],
    [0, d, h],
  ];
  const f = [
    [0, 2, 1],
    [0, 3, 2],
    [4, 5, 6],
    [4, 6, 7],
    [0, 1, 5],
    [0, 5, 4],
    [1, 2, 6],
    [1, 6, 5],
    [2, 3, 7],
    [2, 7, 6],
    [3, 0, 4],
    [3, 4, 7],
  ];
  const n = (a: number[], b: number[], c: number[]) => {
    const u = b.map((x, i) => x - a[i]);
    const w2 = c.map((x, i) => x - a[i]);
    const cr = [
      u[1] * w2[2] - u[2] * w2[1],
      u[2] * w2[0] - u[0] * w2[2],
      u[0] * w2[1] - u[1] * w2[0],
    ];
    const l = Math.hypot(...cr) || 1;
    return cr.map((x) => x / l);
  };
  let out = `solid ${slug(name)}\n`;
  for (const [a, b, c] of f) {
    const nn = n(v[a], v[b], v[c]);
    out += ` facet normal ${nn.join(" ")}\n  outer loop\n   vertex ${v[a].join(" ")}\n   vertex ${v[b].join(" ")}\n   vertex ${v[c].join(" ")}\n  endloop\n endfacet\n`;
  }
  return out + `endsolid ${slug(name)}\n`;
}

export function brief(args: {
  name: string;
  workshopName: string;
  kindLabel: string;
  stageLabel: string;
  tagline: string;
  notes: { who: string; part: number | null; topic?: string | null; text: string }[];
  drafts: { n: number; label: string; stage: string }[];
  topics?: [id: string, label: string][];
}): string {
  const line = (x: {
    who: string;
    part: number | null;
    text: string;
  }) =>
    `- **${x.who === "you" ? "You" : "Apprentice"}${x.part ? ` (part ${x.part})` : ""}:** ${x.text}`;
  const grouped =
    args.topics && args.notes.some((x) => x.topic);
  let notes: string;
  if (grouped && args.topics) {
    const topics = args.topics;
    const sections: string[] = [];
    const general = args.notes.filter((x) => !x.topic);
    if (general.length > 0) {
      sections.push(`### General\n${general.map(line).join("\n")}`);
    }
    for (const [id, label] of topics) {
      const group = args.notes.filter((x) => x.topic === id);
      if (group.length > 0) {
        sections.push(`### ${label}\n${group.map(line).join("\n")}`);
      }
    }
    notes = sections.join("\n") || "—";
  } else {
    notes = args.notes.map(line).join("\n") || "—";
  }
  const drafts =
    args.drafts.map((x) => `${x.n}. ${x.label} (${x.stage})`).join("\n") ||
    "—";
  return `# ${args.name}\n\nWorkshop: ${args.workshopName}  \nKind: ${args.kindLabel}  \nStage: ${args.stageLabel}\n\n## What it is\n${args.tagline || "—"}\n\n## Decisions and notes\n${notes}\n\n## Drafts\n${drafts}\n`;
}
